import { enterWorkspace } from './space-browser-entry.mjs';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const base = process.env.SPACE_BASE_URL || 'http://localhost:8888';
const evidence = path.resolve('output/playwright/space-profile');
await mkdir(evidence, { recursive: true });
const browser = await chromium.launch();
const checks = [];
const errors = [];
try {
  for (const [language, prefix, label] of [['zh', '/zh', '空间'], ['en', '', 'Space']]) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}${prefix}/`, { waitUntil: 'domcontentloaded' });
    assert.equal(await page.locator('#menu > li').count(), 2);
    assert.equal(await page.locator(`#menu a[href$="${prefix}/projects/"]`).innerText(), label);
    await page.goto(`${base}${prefix}/projects/`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready === 'true');
    await enterWorkspace(page);
    await page.waitForFunction(()=>document.querySelector('[data-bear-workspace]').dataset.cafeMode==='desktop');
    assert.match(await page.locator('[data-space-menu-trigger]').getAttribute('aria-label'), /CUBXXW\s*OS/);
    await page.locator('[data-space-window="welcome"] [data-payload="identity"]').click();
    const profile = page.locator('[data-space-window="welcome"] [data-space-profile]');
    assert.equal(await profile.count(), 1);
    assert.equal(await profile.locator('[data-profile-chapter]').count(), 5);
    await profile.locator('[data-profile-chapter] details').first().evaluate(element => { element.open = true; });
    assert.ok((await profile.locator('[data-profile-chapter] details').first().innerText()).length > 40);
    assert.equal(await profile.locator('a[href="/data/identity.json"]').count(), 1);
    await profile.locator(':scope > summary').click();
    assert.equal(await profile.getAttribute('open'), null);
    await page.locator('[data-space-window="welcome"] [data-payload="identity"]').click();
    assert.notEqual(await profile.getAttribute('open'), null);
    await profile.locator('[data-profile-target="story"]').click();
    await page.locator('[data-space-window="welcome"] [data-payload="identity"]').click();
    await page.waitForFunction(() => document.activeElement?.getAttribute('data-profile-section') === 'identity');
    assert.equal(await page.evaluate(() => document.activeElement?.getAttribute('data-profile-section')), 'identity');
    await page.screenshot({ path: path.join(evidence, `${language}-profile-desktop.png`) });
    await page.locator('[data-space-dock] [data-open="notes"]').click();
    await page.locator('[data-note-editor]').fill(`Preserve this note: ${language}`);
    await page.goto(`${base}${prefix}/about/#identity`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready === 'true');
    assert.match(new URL(page.url()).pathname, /\/projects\/$/);
    assert.equal(new URL(page.url()).hash, '#identity');
    assert.equal(await page.locator('[data-space-window="welcome"]').isVisible(), true);
    await page.locator('[data-space-dock] [data-open="notes"]').click();
    assert.equal(await page.locator('[data-note-editor]').inputValue(), `Preserve this note: ${language}`);
    await page.locator('[data-space-menu-trigger]').click();
    await page.locator('.space-menu [data-product-view-button="lab"]').click();
    assert.equal(await page.locator('[data-product-panel="lab"]').isVisible(), true);
    await page.locator('[data-product-view-button="bear"]').click();
    assert.equal(await page.locator('[data-bear-workspace]').isVisible(), true);
    await page.locator('[data-space-dock] [data-open="welcome"]').click();
    await page.screenshot({ path: path.join(evidence, `${language}-desktop.png`) });
    await page.locator('[data-space-menu-trigger]').click();
    await page.locator('[data-space-menu-trigger]').press('Escape');
    assert.equal(await page.locator('.space-menu').isVisible(), false);
    await page.locator('[data-space-dock] [data-open="settings"]').click();
    await page.locator('[data-set-theme="dark"]').click();
    await page.locator('[data-space-dock] [data-open="welcome"]').click();
    await page.screenshot({ path: path.join(evidence, `${language}-desktop-dark.png`) });
    await page.locator('[data-space-dock] [data-open="settings"]').click();
    await page.locator('[data-set-theme="light"]').click();
    await page.locator('[data-space-dock] [data-open="welcome"]').click();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${base}${prefix}/projects/#story`, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready === 'true');
    assert.equal(await page.locator('[data-space-window="welcome"]').isVisible(), true);
    assert.equal(await page.locator('[data-space-dock] [data-mobile-destination]').count(), 5);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: path.join(evidence, `${language}-mobile.png`) });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.space-os-icon').evaluate(element => getComputedStyle(element).animationName), 'none');
    checks.push(`${language}: unified navigation, profile, old About fragment, notes, both views, dark theme, mobile, keyboard menu, reduced motion`);
    await page.close();
  }
  const staticPage = await browser.newPage({ javaScriptEnabled: false });
  await staticPage.goto(`${base}/zh/projects/`, { waitUntil: 'domcontentloaded' });
  assert.equal(await staticPage.locator('noscript [data-profile-chapter]').count(), 5);
  assert.equal(await staticPage.locator('noscript [data-space-profile]').isVisible(), true);
  await staticPage.locator('noscript [data-space-profile] > summary').click();
  assert.equal(await staticPage.locator('noscript [data-profile-section="identity"]').isVisible(), true);
  await staticPage.goto(`${base}/zh/about/#identity`, { waitUntil: 'domcontentloaded' });
  assert.equal(await staticPage.locator('noscript #identity').isVisible(), true);
  checks.push('profile remains readable without JavaScript');
  assert.deepEqual(errors, []);
  await writeFile(path.join(evidence, 'acceptance.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks, errors }));
} finally {
  await browser.close();
}
