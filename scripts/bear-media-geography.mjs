// Regenerates a dependency-free SVG from public-domain Natural Earth 1:110m land.
// world-atlas 2.0.2 redistributes Natural Earth 4.1.0: https://github.com/topojson/world-atlas
// Data terms: https://www.naturalearthdata.com/about/terms-of-use/
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const source = 'https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json';
const response = process.argv[2] ? null : await fetch(source, { redirect: 'error', signal: AbortSignal.timeout(15000) });
if (response && !response.ok) throw new Error('Natural Earth source unavailable');
const bytes = process.argv[2] ? await readFile(process.argv[2]) : Buffer.from(await response.arrayBuffer());
const data = JSON.parse(bytes.toString('utf8'));
const arcs = data.arcs.map(arc => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * data.transform.scale[0] + data.transform.translate[0], y * data.transform.scale[1] + data.transform.translate[1]]; });
});
const ring = ids => ids.flatMap((id, i) => { const points = id < 0 ? [...arcs[~id]].reverse() : arcs[id]; return i ? points.slice(1) : points; });
const geometry = data.objects.land.geometries[0];
const polygons = geometry.type === 'MultiPolygon' ? geometry.arcs : [geometry.arcs];
const paths = [];
for (const polygon of polygons) {
  for (const ids of polygon) {
    const points = ring(ids), lons = points.map(p => p[0]);
    // Antarctica crosses the entire antimeridian; leave the polar cap outside this travel map.
    if (Math.max(...lons) - Math.min(...lons) > 300) continue;
    paths.push(points.map(([lon, lat], i) => `${i ? 'L' : 'M'}${((lon + 180) * 2).toFixed(1)},${((90 - lat) * 2).toFixed(1)}`).join('') + 'Z');
  }
}
const file = new URL('../assets/js/space/media-state.mjs', import.meta.url);
const current = await readFile(file, 'utf8');
const generated = `// BEGIN NATURAL EARTH LAND — generated by scripts/bear-media-geography.mjs\n// Natural Earth 4.1.0, public domain; world-atlas 2.0.2, sha256 ${createHash('sha256').update(bytes).digest('hex')}\n// ${source}\nexport const LAND_PATH = ${JSON.stringify(paths.join(''))};\n// END NATURAL EARTH LAND`;
await writeFile(file, current.replace(/\/\/ BEGIN NATURAL EARTH LAND[\s\S]*?\/\/ END NATURAL EARTH LAND/, generated));
console.log(`Embedded Natural Earth land: ${paths.length} rings, ${paths.join('').length} SVG characters.`);
