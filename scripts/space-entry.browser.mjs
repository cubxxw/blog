import { enterWorkspace } from './space-browser-entry.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';
import { createOutputServer } from './serve-site-output.mjs';
const evidence = path.resolve(process.env.SPACE_EVIDENCE_DIR || 'output/playwright/space-entry');
await fs.mkdir(evidence, { recursive: true });
const server = createOutputServer({ publicDir:path.resolve(process.env.SITE_PUBLIC_DIR || 'public') });
await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
const base = process.env.SPACE_DEV_URL || `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({headless:true});
const results = [];
try {
  for (const lang of ['zh','en']) for (const width of [320,390,768,1440]) for (const theme of ['light','dark']) {
    const context = await browser.newContext({viewport:{width,height:width<=390?844:900},reducedMotion:'reduce'});
    const page = await context.newPage(), errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request',request => requests.push(request.url()));
    await page.route('**/*',route => route.request().url().startsWith(base)?route.continue():route.abort());
    await page.goto(`${base}${lang==='zh'?'/zh':''}/projects/`,{waitUntil:'domcontentloaded'});
    await page.waitForFunction(() => window.BearSpace && document.querySelector('[data-bear-workspace]').dataset.ready === 'true');
    await page.evaluate(theme => window.BearSpace.execute('theme',{value:theme}),theme);
    assert.equal(await page.locator('[data-space-cafe]').isVisible(),true);
    assert.equal(await page.locator('[data-space-window]:visible').count(),0);
    await enterWorkspace(page);
    assert.equal(await page.locator('[data-space-window]:visible').count(),1);
    assert.equal(await page.locator('.space-menubar,.space-desktop-icons,.space-signature').count(),0);
    assert.equal(await page.locator('.product-view-switch').isVisible(),false);
    assert.equal(await page.locator('[data-space-profile]').isVisible(),true);
    assert.equal(await page.locator('[data-space-icons]').evaluate(template => template.content.querySelectorAll('.space-icon').length),11);
    const dock = await page.locator('[data-space-dock]').boundingBox();
    assert.ok(dock.x>=0 && dock.x+dock.width<=width);
    if(width<=390) for (const item of await page.locator('[data-space-dock] button:visible').all()) {
      const box=await item.boundingBox(); assert.ok(box.width>=44 && box.height>=44);
    }
    assert.equal(await page.locator('[data-bear-workspace]').getAttribute('data-world-travel'),'false','reduced motion skips automatic camera travel');
    await page.screenshot({path:path.join(evidence,`${lang}-${width}-${theme}.png`)});
    await page.locator('[data-space-menu-trigger]').click(); await page.locator('.space-menu [data-space-launchpad-trigger]').click();
    assert.equal(await page.locator('[data-space-launchpad]').isVisible(),true);
    assert.equal(await page.locator('[data-launchpad-app]').count(),11);
    await page.keyboard.press('Escape');
    await page.locator('[data-space-menu-trigger]').click();
    assert.equal(await page.locator('.space-menu').isVisible(),true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-space-menu-trigger]').evaluate(el => el===document.activeElement),true);
    await page.locator('[data-space-dock] [data-open="settings"]').click();
    const before=await page.evaluate(() => {window.BearSpace.execute('note',{text:'A private note · 私人笔记'});window.BearSpace.execute('draft',{text:'Draft kept across language'});window.BearSpace.execute('wallpaper',{value:'dusk'});return window.BearSpace.snapshot();});
    const target=lang==='zh'?'en':'zh';
    await page.locator(`[data-set-language="${target}"]`).click();
    await page.waitForURL(`${base}${target==='zh'?'/zh':''}/projects/`);
    await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready==='true');
    assert.equal(await page.locator('[data-space-window="settings"]').isVisible(),true);
    assert.equal(await page.locator(`[data-set-language="${target}"]`).getAttribute('aria-pressed'),'true');
    const after=await page.evaluate(() => window.BearSpace.snapshot());
    for (const key of ['note','draft','theme','wallpaper','windows','favorites','active']) assert.deepEqual(after[key],before[key],key);
    assert.deepEqual(errors,[]);
    results.push({lang,width,theme,checks:'onboarding, clean desktop, menu, Dock, language and preserved state'});
    console.log('PASS',lang,width,theme);
    await context.close();
  }
  const routed = await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const routedPage = await routed.newPage();
  await routedPage.goto(`${base}/zh/projects/?profile=about#identity`);
  await routedPage.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready==='true');
  await routedPage.locator('[data-space-dock] [data-open="settings"]').click();
  await routedPage.locator('[data-set-language="en"]').click();
  await routedPage.waitForURL(`${base}/projects/?profile=about#identity`);
  await routedPage.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready==='true');
  assert.equal(await routedPage.evaluate(() => window.BearSpace.snapshot().active),'settings','language changes must not replay an old profile deep link over Settings');
  await routed.close();
  console.log('PASS language preserves legacy profile URL without stealing the active window');
  const readingContext=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'}), reading=await readingContext.newPage();
  await reading.goto(`${base}/zh/projects/`);
  await reading.waitForFunction(() => window.BearSpace);
  const articleURL=await reading.evaluate(() => {
    const catalog=JSON.parse(document.querySelector('[data-space-catalog]').textContent);
    const article=catalog.articles[0];
    window.BearSpace.execute('open',{app:'reader',payload:article.url});
    window.BearSpace.execute('favorite',{url:article.url});
    return article.url;
  });
  await reading.locator('[data-reader-body] .post-content').waitFor();
  const originalText=await reading.locator('[data-reader-body]').innerText();
  await reading.locator('[data-space-dock] [data-open="settings"]').click();
  await reading.locator('[data-set-language="en"]').click();
  await reading.waitForURL(`${base}/projects/`);
  await reading.waitForFunction(() => window.BearSpace);
  await reading.locator('[data-space-dock] [data-open="reader"]').click();
  await reading.locator('[data-reader-body] .post-content').waitFor();
  assert.equal(await reading.locator('[data-reader-body]').innerText(),originalText,'switching the interface language keeps the original open document');
  await reading.locator('[data-open="reader"][data-payload=""]').click();
  await reading.locator('[data-library-filter="favorites"]').click();
  assert.equal(await reading.locator(`[data-library-list] [data-payload="${articleURL}"]`).count(),1,'bookmarks from either language stay discoverable');
  await readingContext.close();
  console.log('PASS language keeps the open article and its bookmark accessible');
  const recovery=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await recovery.addInitScript(() => localStorage.setItem('bear-space:v1',JSON.stringify({version:1,initialized:true,windows:[{id:'notes',app:'notes',payload:'',rect:{x:20,y:20,width:500,height:400},minimized:false,maximized:false}],active:'notes',note:'Existing private note'})));
  const recovering=await recovery.newPage();
  await recovering.goto(`${base}/zh/projects/`);
  await recovering.waitForFunction(() => window.BearSpace);
  assert.equal(await recovering.locator('[data-space-window]:visible').count(),0);
  const beforeCafeEscape=await recovering.evaluate(()=>window.BearSpace.snapshot());
  await recovering.keyboard.press('Escape');
  assert.deepEqual(await recovering.evaluate(()=>window.BearSpace.snapshot()),beforeCafeEscape,'Escape in the café cannot minimize a hidden window');
  await enterWorkspace(recovering);
  assert.equal(await recovering.locator('[data-space-window="notes"]').isVisible(),true,'opening the computer restores the prior workspace');
  assert.equal(await recovering.locator('[data-note-editor]').inputValue(),'Existing private note');
  await recovering.goto(`${base}/zh/projects/`);
  await recovering.waitForFunction(() => window.BearSpace);
  assert.equal(await recovering.locator('[data-space-window]:visible').count(),0);
  assert.equal(await recovering.locator('[data-space-cafe]').isVisible(),true,'a normal entry opens the café even after an earlier visit');
  assert.equal(await recovering.evaluate(() => window.BearSpace.snapshot().note),'Existing private note');
  await recovery.close();
  console.log('PASS the café preserves an existing workspace and its Escape key');
  const unavailable=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await unavailable.addInitScript(() => {const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(this===localStorage)throw new DOMException('No storage','QuotaExceededError');return original.call(this,key,value);};});
  const unsaved=await unavailable.newPage();
  await unsaved.goto(`${base}/zh/projects/`);
  await unsaved.waitForFunction(() => window.BearSpace);
  await unsaved.evaluate(() => window.BearSpace.execute('note',{text:'Unsaved private note'}));
  await enterWorkspace(unsaved);
  await unsaved.locator('[data-space-dock] [data-open="settings"]').click();
  await unsaved.locator('[data-set-language="en"]').click();
  assert.equal(new URL(unsaved.url()).pathname,'/zh/projects/');
  assert.equal(await unsaved.evaluate(() => window.BearSpace.snapshot().note),'Unsaved private note');
  const downloaded=unsaved.waitForEvent('download');
  await unsaved.locator('[data-space-export]').click();
  const exported=await downloaded;
  const exportedState=JSON.parse(await fs.readFile(await exported.path(),'utf8'));
  assert.equal(exportedState.note,'Unsaved private note');
  await unavailable.close();
  console.log('PASS failed storage blocks navigation and the unsaved note can be exported');
  const sessionless=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  await sessionless.addInitScript(() => {const original=Storage.prototype.setItem;Storage.prototype.setItem=function(key,value){if(this===sessionStorage)throw new DOMException('No session storage','QuotaExceededError');return original.call(this,key,value);};});
  const sessionPage=await sessionless.newPage();
  await sessionPage.goto(`${base}/zh/projects/?profile=about#identity`);
  await sessionPage.waitForFunction(() => window.BearSpace);
  await sessionPage.locator('[data-space-dock] [data-open="settings"]').click();
  const sessionBefore=await sessionPage.evaluate(() => window.BearSpace.snapshot());
  await sessionPage.locator('[data-set-language="en"]').click();
  await sessionPage.waitForURL(`${base}/projects/?profile=about#identity`);
  await sessionPage.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready==='true');
  assert.deepEqual(await sessionPage.evaluate(() => window.BearSpace.snapshot()),sessionBefore);
  assert.equal(await sessionPage.locator('[data-space-window="settings"]').isVisible(),true);
  await sessionless.close();
  console.log('PASS session storage failure uses a temporary URL signal and keeps Settings');




  const context=await browser.newContext({viewport:{width:1440,height:900}}), page=await context.newPage();
  await page.goto(`${base}/zh/projects/`);
  await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.ready==='true');
  await enterWorkspace(page);
  await page.waitForFunction(() => document.querySelector('[data-bear-workspace]')?.dataset.cafeMode==='desktop');
  assert.equal(await page.locator('[data-bear-workspace]').getAttribute('data-world-travel'),'false','camera travel must release after reaching the computer');
  await page.screenshot({path:path.join(evidence,'desktop-entrance-complete.png')});
  await context.close();
  await fs.writeFile(path.join(evidence,'results.json'),JSON.stringify(results,null,2));
  console.log('PASS café camera entrance completes and releases its animation');
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
